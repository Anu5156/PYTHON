#ARITHMATIC:
#+  -  *  /  //  %  **
print(5 / 2)   # 2.5
print(5 // 2)  # 2
print(5 % 2)   # 1
print(2 ** 3)  # 8
"""🧠 KEY DIFFERENCE
/ → float division
// → floor division"""


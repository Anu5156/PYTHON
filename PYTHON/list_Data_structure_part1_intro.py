#stack
"""it follows the first In First Out (FIFO) principle, where the first element added to the stack is the first one to be removed. It is commonly used for function calls, expression evaluation, and backtracking algorithms. The main operations of a stack include push (adding an element), pop (removing the top element), and peek (viewing the top element without removing it)."""

#Queue
"""it follows the First In First Out (FIFO) principle, where the first element added to the queue is the first one to be removed. It is commonly used for task scheduling, buffer management, and breadth-first search algorithms. The main operations of a queue include enqueue (adding an element), dequeue (removing the front element), and front (viewing the front element without removing it)."""

#key kind of data structure

#Tree
"""A tree is a hierarchical data structure that consists of nodes connected by edges. It is used to represent relationships between data in a parent-child manner. Each node in a tree can have zero or more child nodes, and there is one root node that serves as the starting point of the tree. Trees are commonly used in various applications such as file systems, databases, and decision-making algorithms. Some common types of trees include binary trees, binary search trees, AVL trees, and B-trees."""

#Graph
"""A graph is a data structure that consists of a set of vertices (also called nodes) and a set of edges that connect pairs of vertices. Graphs can be directed or undirected, depending on whether the edges have a direction associated with them. They are used to represent relationships between data in various applications such as social networks, transportation networks, and computer networks. Common operations on graphs include traversal (e.g., depth-first search and breadth-first search), pathfinding (e.g., Dijkstra's algorithm), and graph coloring."""

